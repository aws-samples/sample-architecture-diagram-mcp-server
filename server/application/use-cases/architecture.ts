// The architecture capabilities: the interactive HTML (one shot), the
// before → after delta, the .drawio paths (auto layout and manual x/y) and the
// standalone validation pass.
import { computeLayout } from "#domain/architecture/layout.ts";
import type { DrawioLayout, LayoutConnectionInput, LayoutGroupInput, LayoutServiceInput } from "#domain/architecture/layout.ts";
import { generateDrawio } from "#domain/architecture/drawio-xml.ts";
import type { DrawioConnection, DrawioGroup, DrawioOptions, DrawioService } from "#domain/architecture/drawio-xml.ts";
import { computeDelta } from "#domain/architecture/delta.ts";
import type { DeltaSummary } from "#domain/architecture/delta.ts";
import type { ValidationReport } from "#domain/architecture/validate.ts";
import type { ResolvedTab } from "#domain/render/html.ts";
import type { Connection, Group, Service, Step } from "#domain/schemas/architecture.ts";
import type { WrittenFile } from "#application/ports/index.ts";
import type { AppDeps } from "./deps.ts";
import { WrittenFiles } from "./files.ts";
import type { SpecRendering, WrittenDiagram } from "./render-spec.ts";

export interface HtmlDiagramResult extends WrittenDiagram {
  /** The tab rail the viewer gets (multi-tab document), else undefined. */
  tabs: ResolvedTab[] | undefined;
}

export interface DeltaInput {
  title: string;
  subtitle?: string;
  outputPath: string;
  before: { services: Service[]; connections: Connection[]; groups?: Group[] };
  after: { services: Service[]; connections: Connection[]; groups?: Group[] };
  direction?: "LR" | "TB";
  defaultView?: "before" | "delta" | "after";
  lang?: string;
}

export interface AutoDrawioInput {
  title: string;
  subtitle?: string;
  outputPath: string;
  region: string;
  services: LayoutServiceInput[];
  connections: LayoutConnectionInput[];
  groups?: LayoutGroupInput[];
  includeUsers: boolean;
}

export interface ManualDrawioInput {
  title: string;
  subtitle?: string;
  outputPath: string;
  services: DrawioService[];
  connections: DrawioConnection[];
  groups?: DrawioGroup[];
  options?: DrawioOptions;
}

export function createArchitecture(deps: AppDeps, rendering: SpecRendering) {
  const { domain, workspace: ws } = deps;

  return {
    /** generate_html_diagram: validate + auto-repair, render, write HTML + spec.json + sidecar. */
    async generateHtmlDiagram(outputPath: string, spec: Record<string, unknown>, { writeSpec }: { writeSpec?: boolean } = {}): Promise<HtmlDiagramResult> {
      const r = await rendering.renderToFile(spec, outputPath, { writeSpec });
      return { ...r, tabs: domain.html.resolveTabs({ sequence: r.spec.sequence, tabs: r.spec.tabs }) };
    },

    /** diagram_delta: one interactive HTML with a Before / Delta / After toggle. */
    diagramDelta(input: DeltaInput): { summary: DeltaSummary; report: ValidationReport; written: WrittenFile[] } {
      const files = new WrittenFiles(ws);
      const out = ws.resolve(input.outputPath);
      const delta = computeDelta(
        { services: input.before.services, connections: input.before.connections, groups: input.before.groups },
        { services: input.after.services, connections: input.after.connections, groups: input.after.groups },
      );
      // Validate + auto-repair the MERGED (union) IR; repair keeps the delta tags.
      const { report, repaired } = domain.validator.validateDiagram({ services: delta.services, connections: delta.connections, groups: delta.groups });
      const html = domain.html.generateHtml(input.title, input.subtitle || "", repaired.services, repaired.connections, {
        groups: repaired.groups, direction: input.direction, lang: input.lang,
        delta: true, deltaSummary: delta.summary, deltaView: input.defaultView || "delta",
      });
      files.text(out, html);
      return { summary: delta.summary, report, written: files.list };
    },

    /** auto_generate_diagram: ELK compound layout → .drawio. */
    async autoGenerateDrawio(input: AutoDrawioInput): Promise<{ layout: DrawioLayout; written: WrittenFile[] }> {
      const files = new WrittenFiles(ws);
      const out = ws.resolve(input.outputPath);
      const allServices: LayoutServiceInput[] = input.includeUsers ? [{ id: "users", service: "Users", shape: "users", category: "general" }, ...input.services] : input.services;
      const layout = await computeLayout({ services: allServices, connections: input.connections, region: input.region, groups: input.groups });
      const xml = generateDrawio(input.title, input.subtitle || "", layout.services, layout.connections, layout.groups, {
        users: layout.users,
        externals: layout.externals,
        steps: layout.badges,
      });
      files.text(out, xml);
      return { layout, written: files.list };
    },

    /** generate_diagram: manual x/y → .drawio. */
    generateDrawio(input: ManualDrawioInput): { written: WrittenFile[] } {
      const files = new WrittenFiles(ws);
      const out = ws.resolve(input.outputPath);
      files.text(out, generateDrawio(input.title, input.subtitle || "", input.services, input.connections, input.groups || [], input.options || {}));
      return { written: files.list };
    },

    /** validate_diagram: the render tools' well-formedness pass, without writing. */
    validateDiagram(input: { services: Service[]; connections: Connection[]; groups?: Group[]; steps?: Step[] }, repair: boolean) {
      return domain.validator.validateDiagram(input, { repair });
    },
  };
}
export type Architecture = ReturnType<typeof createArchitecture>;
