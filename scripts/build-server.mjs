// Bundle the TypeScript MCP server (server/main/*.ts) into dist/server/ with
// esbuild. npm dependencies stay external (installed with the package); the
// core sources (@core/*), the JSON data and the HTML templates are bundled in.
// The output is committed, so `node mcp-server.js` and `npx github:…` work
// from a clone or a git install without a build step.
//
//   node scripts/build-server.mjs          write dist/server/
//   node scripts/build-server.mjs --check  fail if the committed bundle is stale
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORE = join(ROOT, "packages/diagram-core/src");
const OUT = join(ROOT, "dist/server");
const ENTRIES = { "mcp-server": "server/main/mcp-server.ts", render: "server/main/render.ts" };
const check = process.argv.includes("--check");

const EXTS = [".ts", ".tsx", ".js", ".jsx", "/index.ts", "/index.tsx", "/index.js", "/index.jsx"];
const coreAlias = {
  name: "core-alias",
  setup(b) {
    b.onResolve({ filter: /^@core\// }, (args) => {
      const base = join(CORE, args.path.slice("@core/".length).replace(/\.(js|jsx|ts|tsx)$/, ""));
      const hit = EXTS.map((e) => base + e).find(existsSync);
      if (!hit) return { errors: [{ text: `cannot resolve ${args.path} in packages/diagram-core/src` }] };
      return { path: hit };
    });
  },
};
const rawText = {
  name: "raw-text",
  setup(b) {
    b.onResolve({ filter: /\?raw$/ }, (args) => ({ path: resolve(args.resolveDir, args.path.slice(0, -4)), namespace: "raw" }));
    b.onLoad({ filter: /.*/, namespace: "raw" }, (args) => ({ contents: readFileSync(args.path, "utf-8"), loader: "text" }));
  },
};

const result = await build({
  absWorkingDir: ROOT,
  entryPoints: ENTRIES,
  outdir: OUT,
  bundle: true,
  splitting: true,
  chunkNames: "chunks/[name]-[hash]",
  format: "esm",
  platform: "node",
  target: "node18",
  packages: "external",
  plugins: [coreAlias, rawText],
  loader: { ".json": "json" },
  jsx: "automatic",
  legalComments: "inline",
  charset: "utf8",
  keepNames: true,
  sourcemap: false,
  metafile: true,
  write: false,
  banner: { js: "// GENERATED by scripts/build-server.mjs from server/ — edit the TypeScript sources, then npm run build:server." },
  logLevel: "warning",
});

let stale = 0;
const expected = new Set();
for (const f of result.outputFiles) {
  const rel = f.path.slice(ROOT.length + 1);
  expected.add(rel);
  let text = f.text;
  // The stdio entry is a bin: keep a shebang first.
  if (rel === "dist/server/mcp-server.js") text = "#!/usr/bin/env node\n" + text.replace(/^#![^\n]*\n/, "");
  const prev = existsSync(f.path) ? readFileSync(f.path, "utf-8") : null;
  if (prev === text) continue;
  if (check) { console.error(`stale: ${rel} (run npm run build:server)`); stale++; continue; }
  mkdirSync(dirname(f.path), { recursive: true });
  writeFileSync(f.path, text);
  console.log(`wrote ${rel}`);
}
if (check && stale) process.exit(1);
if (check) console.log(`dist/server is up to date (${expected.size} files).`);
