// Bundle the TypeScript MCP server (server/main/*.ts) into dist/server/ with
// esbuild. npm dependencies stay external (installed with the package); the
// core (through its public entries, "source" condition), the JSON data and the
// HTML templates are bundled in.
// The output is committed, so `node mcp-server.js` and `npx github:…` work
// from a clone or a git install without a build step.
//
//   node scripts/build-server.mjs          write dist/server/
//   node scripts/build-server.mjs --check  fail if the committed bundle is stale
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ROOT, serverBuildOptions } from "./server-esbuild.mjs";

const OUT = join(ROOT, "dist/server");
const ENTRIES = { "mcp-server": "server/main/mcp-server.ts", render: "server/main/render.ts" };
const check = process.argv.includes("--check");

const result = await build({
  ...serverBuildOptions,
  entryPoints: ENTRIES,
  outdir: OUT,
  splitting: true,
  chunkNames: "chunks/[name]-[hash]",
  metafile: true,
  banner: { js: "// GENERATED by scripts/build-server.mjs from server/ — edit the TypeScript sources, then npm run build:server." },
});

let stale = 0;
const expected = new Set();
for (const f of result.outputFiles) {
  const rel = f.path.slice(ROOT.length + 1);
  expected.add(rel);
  let text = f.text;
  // The stdio entry is a bin: keep a shebang first.
  if (rel === "dist/server/mcp-server.js") text = "#!/usr/bin/env node\n" + text.replace(/^#![^\n]*\n/, "");
  const prev = existsSync(f.path) ? readFileSync(f.path, "utf-8") : null;
  if (prev === text) continue;
  if (check) { console.error(`stale: ${rel} (run npm run build:server)`); stale++; continue; }
  mkdirSync(dirname(f.path), { recursive: true });
  writeFileSync(f.path, text);
  console.log(`wrote ${rel}`);
}
// Files left over from an earlier build (chunk names carry a content hash).
const list = (d) => (existsSync(d) ? readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? list(join(d, e.name)) : [join(d, e.name)])) : []);
for (const p of list(OUT)) {
  const rel = p.slice(ROOT.length + 1);
  if (expected.has(rel)) continue;
  if (check) { console.error(`extra: ${rel} (run npm run build:server)`); stale++; continue; }
  rmSync(p);
  console.log(`removed ${rel}`);
}
if (check && stale) process.exit(1);
if (check) console.log(`dist/server is up to date (${expected.size} files).`);
