// The flow and sequence HTML players run the core's layout code in the browser:
// a classic <script> gets the module's source with its `export` keywords
// dropped. Those modules are TypeScript, so this script compiles them to plain
// JavaScript (types stripped, nothing else changed) and writes the result as
// string constants the server bundles:
//   server/assets/generated/inline-scripts.ts
// The inlined modules must stay self-contained (no imports).
//
//   node scripts/build-inline-scripts.mjs          write the file
//   node scripts/build-inline-scripts.mjs --check  fail if it is stale
import { transform } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORE = join(ROOT, "packages/diagram-core/src");
const OUT = join(ROOT, "server/assets/generated/inline-scripts.ts");
const MODULES = { FLOW_LAYOUT_JS: "flowLayout", SEQUENCE_LAYOUT_JS: "sequenceLayout", CODE_BLOCKS_JS: "codeBlocks" };

async function classicScript(name) {
  const ts = join(CORE, `${name}.ts`);
  const js = join(CORE, `${name}.js`);
  const file = existsSync(ts) ? ts : js;
  const src = readFileSync(file, "utf-8");
  if (/^\s*import\s/m.test(src)) throw new Error(`${file}: inlined modules must not import anything`);
  const code = file.endsWith(".ts")
    ? (await transform(src, { loader: "ts", format: "esm", target: "es2020", legalComments: "inline", sourcefile: file })).code
    : src;
  return code.replace(/^export /gm, "");
}

let body = "// GENERATED by scripts/build-inline-scripts.mjs from packages/diagram-core/src — do not edit.\n"
  + "// Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.\n// SPDX-License-Identifier: MIT-0\n";
for (const [constName, mod] of Object.entries(MODULES)) {
  body += `\n/** ${mod} as a classic-script body (exports dropped). */\nexport const ${constName}: string = ${JSON.stringify(await classicScript(mod))};\n`;
}

const prev = existsSync(OUT) ? readFileSync(OUT, "utf-8") : null;
if (process.argv.includes("--check")) {
  if (prev !== body) { console.error("stale: server/assets/generated/inline-scripts.ts (run npm run build:inline)"); process.exit(1); }
  console.log("inline scripts are up to date.");
} else if (prev !== body) {
  writeFileSync(OUT, body);
  console.log("wrote server/assets/generated/inline-scripts.ts");
}
